import {writeFileSync} from 'node:fs';
import {products} from '../src/config/products.ts';
import {normalizeProduct,parseAdminData} from '../src/Components/dashboards/adminModel.ts';
import {emptyWorkspace} from '../src/Components/dashboards/businessModel.ts';

// Initializes the private editor from the existing public catalog. It never
// publishes changes, imports browser data, or replaces a configured workspace.
const data=parseAdminData(JSON.stringify({version:1,posts:[],publicProjects:[],trash:[],history:[],activity:[],workspace:emptyWorkspace(),products:products.map(product=>normalizeProduct({...product,id:product.slug,logo:product.logo??'',editorialStatus:'draft',updatedAt:''}))}));
const json=JSON.stringify(data);
if(json.includes('$ksoft_seed$'))throw new Error('Unsafe SQL seed delimiter');
const sql=`-- Generated by scripts/generate-supabase-seed.mjs. No credentials.
-- Safe to repeat: an initialized workspace is never replaced.
begin;
do $setup$
declare seed jsonb := $ksoft_seed$${json}$ksoft_seed$::jsonb;
begin
  perform 1 from public.ksoft_workspace where id for update;
  if exists(select 1 from public.ksoft_workspace where id and metadata is not null) then
    raise notice 'Ksoft workspace already initialized; skipping seed';
    return;
  end if;
  insert into public.ksoft_records(module,id,position,payload)
  select 'products',item->>'id',position::integer,item
  from jsonb_array_elements(seed->'products') with ordinality as t(item,position);
  update public.ksoft_workspace
  set metadata=jsonb_set(seed-'products'-'posts'-'publicProjects','{workspace,records}','{}'::jsonb),revision=revision+1,updated_at=now()
  where id;
end $setup$;
commit;
`;
writeFileSync(new URL('../supabase/seed.sql',import.meta.url),sql);
console.log('Seed privado generado; no se publica ni modifica el contenido existente.');
