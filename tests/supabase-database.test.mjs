import assert from 'node:assert/strict';
import {test} from 'node:test';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
import {emptyWorkspace} from '../src/Components/dashboards/businessModel.ts';
const admin='00000000-0000-4000-8000-000000000001';
const outsider='00000000-0000-4000-8000-000000000002';
const record=(id,values)=>({id,values,createdAt:'2026-10-23T12:00:00Z',updatedAt:'2026-10-23T12:00:00Z'});
test('Supabase SQL enforces private access, atomic revisions, publication and server-only intake',async()=>{
  const db=new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role; create schema auth; create schema storage;
      create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      create function auth.role() returns text language sql stable as $$ select current_setting('request.jwt.claim.role',true) $$;
      grant usage on schema auth to anon,authenticated,service_role;
      create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
      create table storage.objects(id uuid,bucket_id text); alter table storage.objects enable row level security;
      insert into auth.users values('${admin}'),('${outsider}');`);
    await db.exec(await readFile(new URL('../supabase/migrations/202610230001_ksoft.sql',import.meta.url),'utf8'));
    await db.exec(await readFile(new URL('../supabase/migrations/202610240002_intake_initial_catalog.sql',import.meta.url),'utf8'));
    await db.exec(`insert into public.ksoft_admins values('${admin}');`);
    const role=async(name,id='')=>{
      await db.exec('reset role');
      await db.query("select set_config('request.jwt.claim.sub',$1,false),set_config('request.jwt.claim.role',$2,false)",[id,name]);
      await db.exec('set role '+name);
    };
    const rpc=async(name,args=[])=>db.query(`select public.${name}(${args.map((_,i)=>'$'+(i+1)).join(',')}) as value`,args);
    await role('anon');
    await assert.rejects(rpc('ksoft_read_workspace'),/permission denied/);
    await assert.rejects(db.query('select * from ksoft_records'),/permission denied/);
    await assert.rejects(rpc('ksoft_receive_enquiry',[{},'x'.repeat(64)]),/permission denied/);
    assert.equal((await db.query('select payload from ksoft_public_site')).rows[0].payload,null);
    await role('authenticated',outsider);
    await assert.rejects(rpc('ksoft_read_workspace'),/FORBIDDEN/);
    await assert.rejects(db.query('insert into ksoft_admins values($1)',[outsider]),/permission denied/);
    await role('authenticated',admin);
    assert.equal((await rpc('ksoft_read_workspace')).rows[0].value.document,null);
    const doc={version:1,posts:[],products:[],publicProjects:[],activity:[],workspace:emptyWorkspace()};
    doc.workspace.records.clients=[record('c',{name:'Cliente',email:'c@example.test',status:'Activo',notes:'PRIVATE NOTE'})];
    doc.workspace.records.quotes=[record('q',{name:'Cotización',client:'c',amount:'500',date:'2026-10-23',status:'Aceptada',scope:'Entregables'})];
    doc.products=[{id:'p',slug:'dental',name:'Dental',editorialStatus:'ready',visibility:'visible',presentation:{},internalSecret:'DO NOT PUBLISH'},{id:'draft',slug:'draft',editorialStatus:'draft',visibility:'visible'}];
    assert.equal((await rpc('ksoft_save_workspace',[doc,0])).rows[0].value,1);
    const loaded=(await rpc('ksoft_read_workspace')).rows[0].value;
    assert.deepEqual(loaded.document,doc);
    await assert.rejects(rpc('ksoft_save_workspace',[doc,0]),/CONFLICT/);
    await assert.rejects(rpc('ksoft_publish_site',[0]),/CONFLICT/);
    const invalid=structuredClone(doc);invalid.workspace.records.payments=[record('bad',{name:'Exceso',client:'c',quote:'q',amount:'501',status:'Pagado'})];
    await assert.rejects(rpc('ksoft_save_workspace',[invalid,1]),/PAYMENT_EXCEEDS_QUOTE/);
    assert.deepEqual((await rpc('ksoft_read_workspace')).rows[0].value,loaded);
    invalid.workspace.records.payments=[];invalid.workspace.records.tasks=[record('t',{name:'Tarea',project:'missing',status:'Pendiente'})];
    await assert.rejects(rpc('ksoft_save_workspace',[invalid,1]),/INVALID_RELATION/);
    await rpc('ksoft_publish_site',[1]);
    await role('anon');
    const published=(await db.query('select payload from ksoft_public_site')).rows[0].payload;
    assert.equal(published.products.length,1);assert.equal(published.products[0].slug,'dental');
    assert.equal(JSON.stringify(published).includes('PRIVATE NOTE'),false);
    assert.equal(JSON.stringify(published).includes('DO NOT PUBLISH'),false);
    await role('service_role');
    const enquiry={name:'Solicitante',email:'new@example.test',message:'Me interesa',product:'dental',purpose:'pilot'};
    await rpc('ksoft_receive_enquiry',[enquiry,'a'.repeat(64)]);
    await assert.rejects(rpc('ksoft_receive_enquiry',[enquiry,'a'.repeat(64)]),/RATE_LIMITED/);
    await assert.rejects(rpc('ksoft_receive_enquiry',[{...enquiry,product:'private-draft'},'b'.repeat(64)]),/INVALID_PRODUCT/);
    await role('authenticated',admin);
    const after=(await rpc('ksoft_read_workspace')).rows[0].value;
    assert.equal(after.revision,2);assert.equal(after.document.workspace.records.requests.length,1);
    assert.equal(after.document.workspace.records.requests[0].values.product,'dental');
    await assert.rejects(rpc('ksoft_save_workspace',[doc,1]),/CONFLICT/);
    await role('anon');
    await assert.rejects(db.query('select * from ksoft_audit'),/permission denied/);
    await db.exec('reset role; update public.ksoft_public_site set payload=null;');
    await role('service_role');
    await rpc('ksoft_receive_enquiry',[{...enquiry,product:'saas-dental'},'c'.repeat(64)]);
    await assert.rejects(rpc('ksoft_receive_enquiry',[{...enquiry,product:'unpublished-draft'},'d'.repeat(64)]),/INVALID_PRODUCT/);
  } finally {await db.close();}
});
